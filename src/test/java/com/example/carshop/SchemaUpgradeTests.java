package com.example.carshop;

import org.junit.jupiter.api.Test;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.context.*;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.dao.DataIntegrityViolationException;
import java.sql.DriverManager;
import static org.junit.jupiter.api.Assertions.*;

@SpringBootTest(properties = {"app.upload-dir=target/upgrade-test-uploads"})
@TestConstructor(autowireMode=TestConstructor.AutowireMode.ALL)
class SchemaUpgradeTests {
    private static final String URL = "jdbc:h2:mem:schema-upgrade;DB_CLOSE_DELAY=-1";
    @DynamicPropertySource
    static void legacyDatabase(DynamicPropertyRegistry registry) throws Exception {
        // A populated table from the original schema, before normalized_name existed.
        try (var connection = DriverManager.getConnection(URL, "sa", "");
             var statement = connection.createStatement()) {
            statement.execute("create table manufacturer (id bigint generated by default as identity primary key, name varchar(80) not null unique, description varchar(500))");
            statement.execute("insert into manufacturer(name) values ('Toyota')");
        }
        registry.add("spring.datasource.url", () -> URL);
        registry.add("spring.jpa.hibernate.ddl-auto", () -> "update");
    }
    private final JdbcTemplate jdbc;
    SchemaUpgradeTests(JdbcTemplate jdbc) { this.jdbc = jdbc; }
    @Test void upgradeComputesKeysForExistingRowsAndEnforcesUniqueness() {
        assertEquals("Toyota", jdbc.queryForObject("select name from manufacturer", String.class));
        assertEquals("toyota", jdbc.queryForObject("select normalized_name from manufacturer", String.class));
        assertThrows(DataIntegrityViolationException.class,
            () -> jdbc.update("insert into manufacturer(name) values ('TOYOTA')"));
    }
}
